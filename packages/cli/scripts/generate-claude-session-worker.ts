import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { build } from "esbuild";

const upstream = resolve(import.meta.dirname, "../src/acp/harness/claude/upstream/src");
const entry = join(upstream, "environment-session-worker.ts");
const output = join(upstream, "generated/environment-session-worker-source.ts");

// Eval Worker code is CommonJS without a module file. The SDK creates a require from import.meta.url
// when it loads, so the bundle supplies the file URL Node gives that code. The banner precedes the
// bundle's own directive, so it restates "use strict".
const result = await build({
    banner: { js: '"use strict";const importMetaUrl = require("node:url").pathToFileURL(__filename).href;' },
    bundle: true,
    define: { "import.meta.url": "importMetaUrl" },
    entryPoints: [entry],
    format: "cjs",
    logLevel: "silent",
    minify: true,
    platform: "node",
    write: false,
});
const [bundle, ...unexpected] = result.outputFiles;
if (result.warnings.length > 0 || bundle === undefined || unexpected.length > 0) {
    throw new Error(
        `The Claude session worker must bundle into one file without warnings: ${JSON.stringify(result.warnings)}`,
    );
}
await mkdir(dirname(output), { recursive: true });
await writeFile(
    output,
    [
        "// Generated by packages/cli/scripts/generate-claude-session-worker.ts. Do not edit.",
        `// Source: ${relative(dirname(output), entry)}`,
        `export const environmentSessionWorkerSource: string = ${JSON.stringify(bundle.text)};`,
        "",
    ].join("\n"),
);
