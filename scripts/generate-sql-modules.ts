import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";

interface MigrationSource {
    readonly name: string;
    readonly path: string;
}

async function sqlFiles(directory: string): Promise<MigrationSource[]> {
    const names = (await readdir(directory)).filter((name) => name.endsWith(".sql")).sort();
    return names.map((name) => ({ name, path: join(directory, name) }));
}

async function writeMigrationModule(
    outputPath: string,
    exportName: string,
    sources: readonly MigrationSource[],
): Promise<void> {
    const migrations = await Promise.all(
        sources.map(async (source) => ({
            name: source.name,
            sql: await readFile(source.path, "utf8"),
        })),
    );
    const sourcePaths = sources.map((source) => relative(dirname(outputPath), source.path));
    const generated = [
        "// Generated by scripts/generate-sql-modules.ts. Do not edit.",
        `// Sources: ${sourcePaths.join(", ")}`,
        `export const ${exportName} = ${JSON.stringify(migrations, undefined, 4)} as const;`,
        "",
    ].join("\n");
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, generated);
}

const root = resolve(import.meta.dirname, "..");
const relayCore = join(root, "packages/relay-core");
const platform = join(root, "packages/relay-cloudflare-platform");

await writeMigrationModule(
    join(platform, "src/generated/session-relay-do-migrations.ts"),
    "sessionRelayDurableObjectMigrations",
    await sqlFiles(join(platform, "migrations/session-relay-do")),
);
await writeMigrationModule(
    join(relayCore, "src/generated/session-do-migrations.ts"),
    "sessionDurableObjectMigrations",
    await sqlFiles(join(relayCore, "migrations/session-do")),
);
await writeMigrationModule(
    join(relayCore, "src/generated/runtime-connection-do-migrations.ts"),
    "runtimeConnectionDurableObjectMigrations",
    await sqlFiles(join(relayCore, "migrations/runtime-connection-do")),
);
await writeMigrationModule(
    join(platform, "src/generated/project-do-migrations.ts"),
    "projectDurableObjectMigrations",
    await sqlFiles(join(platform, "migrations/project-do")),
);
