import { randomUUID } from "node:crypto";
import { mkdir, readdir, readFile, rename, unlink, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";

interface MigrationSource {
    readonly name: string;
    readonly path: string;
}

async function sqlFiles(directory: string): Promise<MigrationSource[]> {
    const entries = await readdir(directory, { withFileTypes: true });
    const sources = await Promise.all(
        entries.map(async (entry): Promise<readonly MigrationSource[]> => {
            const path = join(directory, entry.name);
            if (entry.isDirectory()) {
                return await sqlFiles(path);
            }
            return entry.name.endsWith(".sql") ? [{ name: relative(directory, path), path }] : [];
        }),
    );
    return sources.flat().toSorted((left, right) => left.path.localeCompare(right.path));
}

async function writeMigrationModule(
    outputPath: string,
    exportName: string,
    sources: readonly MigrationSource[],
): Promise<void> {
    const migrations = await Promise.all(
        sources.map(async (source) => ({
            name: source.name,
            sql: await readFile(source.path, "utf8"),
        })),
    );
    const sourcePaths = sources.map((source) => relative(dirname(outputPath), source.path));
    const generated = [
        "// Generated by scripts/generate-sql-modules.ts. Do not edit.",
        `// Sources: ${sourcePaths.join(", ")}`,
        `export const ${exportName} = ${JSON.stringify(migrations, undefined, 4)} as const;`,
        "",
    ].join("\n");
    await mkdir(dirname(outputPath), { recursive: true });
    // Parallel package checks may generate this module while another compiler reads it.
    const temporaryPath = `${outputPath}.${randomUUID()}.tmp`;
    try {
        await writeFile(temporaryPath, generated, { flag: "wx" });
        await rename(temporaryPath, outputPath);
    } catch (cause) {
        await unlink(temporaryPath).catch(() => undefined);
        throw cause;
    }
}

const root = resolve(import.meta.dirname, "..");
const cli = join(root, "packages/cli");
const relayCore = join(root, "packages/relay-core");
const platform = join(root, "packages/relay-cloudflare-platform");
const recording = join(root, "packages/recording-cloudflare");

await writeMigrationModule(
    join(cli, "src/engine/generated/command-cancellation-migrations.ts"),
    "commandCancellationMigrations",
    await sqlFiles(join(cli, "migrations/command-cancellation")),
);
